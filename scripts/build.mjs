// Build step: convert Claude-design `.dc.html` exports into data the Next app renders.
// - extracts each page's <x-dc> inner template (the real markup)
// - inlines the shared ClipNav / ClipFooter components
// - rewrites *.dc.html links to Next routes and resolves {{ brand }}
// - pulls each page's <script data-dc-script> body so the client runtime can run it verbatim
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = join(__dirname, '..', 'extracted');
const OUT = join(__dirname, '..', 'lib');
mkdirSync(OUT, { recursive: true });

const BRAND = 'Go Unmanual';

// source file -> { route, slug used as nav active key }
const PAGES = {
  Clipupp:     { route: '/',             active: 'home' },
  Services:    { route: '/services',     active: 'services' },
  Solutions:   { route: '/solutions',    active: 'solutions' },
  CaseStudies: { route: '/case-studies', active: 'cases' },
  Pricing:     { route: '/pricing',      active: 'pricing' },
  About:       { route: '/about',        active: 'about' },
  Contact:     { route: '/contact',      active: 'contact' },
};

// map every *.dc.html href to its Next route
const LINK_MAP = {
  'Clipupp.dc.html': '/',
  'Services.dc.html': '/services',
  'Solutions.dc.html': '/solutions',
  'CaseStudies.dc.html': '/case-studies',
  'Pricing.dc.html': '/pricing',
  'About.dc.html': '/about',
  'Contact.dc.html': '/contact',
};

function read(name) {
  return readFileSync(join(SRC, `${name}.dc.html`), 'utf8');
}

// slice the inner template between <x-dc> ... </x-dc>
function xdcInner(src) {
  const open = src.indexOf('<x-dc>');
  const close = src.lastIndexOf('</x-dc>');
  return src.slice(open + '<x-dc>'.length, close);
}

// remove the <helmet>...</helmet> block (fonts/keyframes live in globals.css)
function stripHelmet(html) {
  return html.replace(/<helmet>[\s\S]*?<\/helmet>/gi, '');
}

// grab the body of the page's <script data-dc-script ...> ... </script>
function scriptBody(src) {
  const m = src.match(/<script[^>]*data-dc-script[^>]*>([\s\S]*?)<\/script>/i);
  return m ? m[1].trim() : '';
}

// extract the <style> CSS inside the first helmet (keyframes + base) — same on every page
function helmetStyle(src) {
  const m = src.match(/<helmet>[\s\S]*?<style>([\s\S]*?)<\/style>[\s\S]*?<\/helmet>/i);
  return m ? m[1].trim() : '';
}

function rewrite(html) {
  // strip the runtime ref attribute
  html = html.replace(/\s*ref="\{\{\s*rootRef\s*\}\}"/g, '');
  // resolve brand
  html = html.replace(/\{\{\s*brand\s*\}\}/g, BRAND);
  // rewrite dc.html links to routes
  for (const [file, route] of Object.entries(LINK_MAP)) {
    html = html.replaceAll(`href="${file}"`, `href="${route}"`);
  }
  return html;
}

// shared components: inner template minus helmet
const navInner = rewrite(stripHelmet(xdcInner(read('ClipNav'))));
const footerInner = rewrite(stripHelmet(xdcInner(read('ClipFooter'))));

const navScript = scriptBody(read('ClipNav'));
const footerScript = scriptBody(read('ClipFooter'));

// resolve <dc-import name="ClipNav" .../> and <dc-import name="ClipFooter" .../>
function inlineImports(html) {
  // self-closing or paired, with arbitrary attrs
  html = html.replace(/<dc-import\b[^>]*\bname=["']ClipNav["'][^>]*>(?:<\/dc-import>)?/gi, navInner);
  html = html.replace(/<dc-import\b[^>]*\bname=["']ClipFooter["'][^>]*>(?:<\/dc-import>)?/gi, footerInner);
  return html;
}

const pagesOut = {};
let globalCss = '';

for (const [name, meta] of Object.entries(PAGES)) {
  const src = read(name);
  if (!globalCss) globalCss = helmetStyle(src);
  let html = rewrite(stripHelmet(xdcInner(src)));
  html = inlineImports(html);
  pagesOut[name] = {
    route: meta.route,
    active: meta.active,
    html,
    script: scriptBody(src),
  };
}

// emit pages data
const pagesFile =
  `// AUTO-GENERATED by scripts/build.mjs — do not edit by hand.\n` +
  `// Re-run \`npm run gen\` after changing files in /extracted.\n` +
  `export const PAGES = ${JSON.stringify(pagesOut, null, 2)};\n`;
writeFileSync(join(OUT, 'pages.generated.js'), pagesFile);

// emit shared scripts
const scriptsFile =
  `// AUTO-GENERATED by scripts/build.mjs — do not edit by hand.\n` +
  `export const NAV_SCRIPT = ${JSON.stringify(navScript)};\n` +
  `export const FOOTER_SCRIPT = ${JSON.stringify(footerScript)};\n`;
writeFileSync(join(OUT, 'scripts.generated.js'), scriptsFile);

// emit the shared keyframes/base CSS
writeFileSync(join(OUT, 'generated.css'), `/* AUTO-GENERATED from extracted helmet <style> */\n${globalCss}\n`);

console.log('Generated', Object.keys(pagesOut).length, 'pages →', OUT);
